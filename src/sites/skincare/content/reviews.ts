/** Reviews for a product, most helpful first. Products the owner adds have none yet. */
export function reviewsFor(slug: string): Review[] {
  return (ROWS[slug] ?? []).map(([name, city, skin, rating, date, helpful, title, body], i) => ({
    id: `${slug}-${i}`,
    slug,
    name,
    city,
    skin,
    rating,
    date,
    helpful,
    title,
    body,
    verified: true,
  }));
}

const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

/** "14 Oct 2026", formatted by hand so the server and browser always agree. */
export function formatReviewDate(iso: string): string {
  const [y, m, d] = iso.slice(0, 10).split("-").map(Number);
  return `${d} ${MONTHS[m - 1]} ${y}`;
}
